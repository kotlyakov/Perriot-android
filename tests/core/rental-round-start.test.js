import test from 'node:test';
import assert from 'node:assert/strict';
import {createRun,dispatch} from '../../src/core/run.js';
import {serializeState,deserializeState} from '../../src/persistence/save.js';
import {currentApkShopContext} from '../../src/core/apk-shop-state.js';
import {getCashout} from '../../src/core/cashout.js';
const fresh=()=>createRun('RENTSTART',{runId:'rent-start',money:4n,referenceRng:true,referenceShop:true});
const joker=(extra={})=>({id:'lease',entityId:'j_joker',rental:true,cost:1n,sellCost:1n,...extra});
const step=(s,type,extra={})=>{const r=dispatch(s,{type,expectedRevision:s.revision,...extra});assert.equal(r.error,null,JSON.stringify(r.error));return r;};
const reload=s=>deserializeState(serializeState(s));

test('rental pays before entered round effects once, including debt; stale/reentry and reload never repay',()=>{
 const before=fresh();before.money=1n;before.jokers=[joker()];before.apkShop.context=currentApkShopContext(before);
 const action={type:'START_BLIND',expectedRevision:before.revision},r=dispatch(before,action);
 assert.equal(r.error,null);assert.equal(r.state.money,-2n);assert.equal(before.money,1n);
 assert.equal(r.events.filter(e=>e.type==='joker_rental_paid').length,1);
 assert.ok(r.events.findIndex(e=>e.type==='joker_rental_paid')<r.events.findIndex(e=>e.type==='round_started'));
 assert.equal(dispatch(r.state,action).error.code,'STALE_ACTION');
 assert.ok(dispatch(r.state,{type:'START_BLIND',expectedRevision:r.state.revision}).error);
 assert.equal(reload(r.state).money,-2n);
 const played=step(reload(r.state),'PLAY_HAND',{cardIds:[r.state.hand[0]]});assert.equal(played.state.money,-2n);assert.equal(played.events.some(e=>e.type==='joker_rental_paid'),false);assert.equal(reload(played.state).money,-2n);
});

test('debuffed eternal and expired perishable rentals pay on start, never on terminal loss',()=>{
 for(const extra of [{debuffed:true},{eternal:true},{perishable:true,perishRounds:0,debuffed:true}]){
  let s=fresh();s.jokers=[joker(extra)];s=step(s,'START_BLIND').state;assert.equal(s.money,1n);
  s.round.handsRemaining=1;const r=step(s,'PLAY_HAND',{cardIds:[s.hand[0]]});assert.equal(r.state.phase,'game_over');assert.equal(r.state.money,1n);assert.equal(r.events.some(e=>e.type==='joker_rental_paid'),false);assert.equal(reload(r.state).money,1n);
 }
});

test('skipping a blind does not charge rent and the next actually entered round does',()=>{
 let s=fresh();s.jokers=[joker()];s.apkBlinds.tags.small='tag_economy';
 const skip=step(s,'SKIP_BLIND');assert.equal(skip.events.some(e=>e.type==='joker_rental_paid'),false);s=skip.state;const before=s.money;s=step(s,'START_BLIND').state;assert.equal(s.money,before-3n);
});

test('rental acquired during a round first pays next start and negative cashout remains valid',()=>{
 let s=step(fresh(),'START_BLIND').state;s.jokers=[joker()];s.money=-1n;s.handLevels.high_card=1000;s.apkShop.context=currentApkShopContext(s);
 const won=step(s,'PLAY_HAND',{cardIds:[s.hand[0]]});s=reload(won.state);assert.equal(s.money,-1n);assert.equal(won.events.some(e=>e.type==='joker_rental_paid'),false);assert.equal(getCashout(s).interest,0n);
 const cash=getCashout(s).total;s=step(s,'CASH_OUT').state;assert.equal(s.money,cash-1n);s=step(s,'LEAVE_SHOP').state;const before=s.money;s=step(s,'START_BLIND').state;assert.equal(s.money,before-3n);
});

test('0.4.58 end-rent journal remains authentic and switches future actions to entry rent',async()=>{
 // Generated by unmodified d485867: $10 before hand, $3 native end-round rent.
 const {readFile}=await import('node:fs/promises');
 const saved=(await readFile(new URL('../fixtures/rental-legacy-058.json',import.meta.url),'utf8')).trim();let s=deserializeState(saved);assert.equal(serializeState(s),saved);
 const rejected=dispatch(s,{type:'START_BLIND',expectedRevision:s.revision-1});assert.equal(rejected.state,s);assert.equal(s.rentalTiming,undefined);
 assert.equal(s.money,7n);assert.equal(s.rentalTiming,undefined);s=step(s,'CASH_OUT').state;
 assert.equal(s.rentalTiming,'round_start');s=reload(s);s=reload(step(s,'LEAVE_SHOP').state);
 const money=s.money;s=reload(step(s,'START_BLIND').state);assert.equal(s.money,money-3n);
 const paid=s.money;s=reload(step(s,'PLAY_HAND',{cardIds:[s.hand[0]]}).state);assert.equal(s.money,paid);
});

